const router = Router();

// Plan-based module switches (see modules/features). Bearer-authenticated calls to a switched-off module get
// 402 FEATURE_DISABLED. Device-key calls and public token links carry no bearer token and fall through to the
// module's own authentication.
const gate = (key) => {
  const check = requireFeature(key);
  return (req, res, next) => {
    if (!req.headers.authorization) return next();
    return authenticate(req, res, (err) => (err ? next(err) : check(req, res, next)));
  };
};

router.get('/health', (_req, res) => {
  const db = mongoose.connection.readyState === 1 ? 'up' : 'down';
  res.status(db === 'up' ? 200 : 503).json({ success: db === 'up', data: { status: 'ok', db, uptime: Math.round(process.uptime()) } });
});

